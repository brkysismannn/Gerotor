"""Generate frontend/js/methods.generated.js (offline copy of the backend methods registry).

Source order: GET <base>/api/methods (default http://127.0.0.1:8770); if that endpoint is not reachable or not
yet available, the same registry is read in-process from backend/api (report.methods(), report.ASSUMPTIONS,
calc.VARIANT_DEFAULTS), i.e. exactly what the endpoint serves. Never edit the output by hand.

Run from anywhere:  python frontend/tools/gen_methods.py [base-url]
"""
import json, pathlib, sys, urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "frontend" / "js" / "methods.generated.js"


def from_endpoint(base):
    with urllib.request.urlopen(base + "/api/methods", timeout=5) as r:
        d = json.load(r)
    if isinstance(d, list):
        d = {"methods": d}
    if "methods" not in d or "assumptions" not in d:
        raise ValueError("endpoint answer has no methods/assumptions")
    h = json.load(urllib.request.urlopen(base + "/api/health", timeout=5))
    return d, "GET " + base + "/api/methods", h.get("git")


def from_process():
    sys.path.insert(0, str(ROOT / "backend"))
    from api import calc, report
    ass = []
    for aid, (name, key, text) in report.ASSUMPTIONS.items():
        ass.append({"id": aid, "name": name, "switch": key, "text": text,
                    "default": calc.VARIANT_DEFAULTS.get(key) if key else None})
    return {"methods": report.methods(), "assumptions": ass}, "in-process api.report (endpoint not reachable)", report.git_hash()


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8770"
    try:
        data, src, git = from_endpoint(base)
    except Exception:
        data, src, git = from_process()
    for m in data["methods"]:                       # drop bulk docstrings, keep what the report prints
        m.pop("description", None); m.pop("functions", None)
    data["source"] = src
    data["backendGit"] = git
    text = ("/* GENERATED by frontend/tools/gen_methods.py from the backend methods registry. Do not edit. */\n"
            "(function (G) { G.methodsData = " + json.dumps(data, indent=1, ensure_ascii=True, sort_keys=True) + "; })(window.Gerotor = window.Gerotor || {});\n")
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT, "from", src, "git", git)


if __name__ == "__main__":
    main()
